test('form mode writes the dialog, data-request on every button and the two script tags inside the markers; WhatsApp mode writes none', () => {
  const form = renderSection(data, FORM);
  const wa = renderSection(data, WA);
  assert.equal((form.match(/<dialog /g) || []).length, 1);
  assert.equal((form.match(/<\/dialog>/g) || []).length, 1);
  assert.ok(form.includes('<script src="site-config.js" defer></script>\n  <script src="plan-request.js" defer></script>'));
  assert.ok(form.indexOf('</dialog>') < form.indexOf('<script src="site-config.js"'), 'the config loads after the dialog markup');
  assert.ok(form.indexOf('plan-request.js') < form.indexOf('</section>'), 'the scripts sit inside the section');
  const kinds = [...form.matchAll(/data-request="([a-z]+)"/g)].map((m) => m[1]);
  assert.equal(kinds.length, 21);
  assert.deepEqual({ plan: kinds.filter((k) => k === 'plan').length, custom: kinds.filter((k) => k === 'custom').length,
    bundle: kinds.filter((k) => k === 'bundle').length, general: kinds.filter((k) => k === 'general').length }, { plan: 15, custom: 1, bundle: 4, general: 1 });
  for (const s of ['<dialog', 'data-request', 'site-config.js', 'plan-request.js', 'request-dialog']) assert.ok(!wa.includes(s), `WhatsApp mode must not write ${s}`);
  // The committed page is the form-mode render, and the dialog sits inside the markers.
  const inside = between(index);
  assert.ok(inside.includes('<dialog class="request-dialog" id="request-dialog"'));
  assert.ok(inside.includes('<script src="plan-request.js" defer></script>'));
  assert.ok(!index.slice(index.indexOf(END)).includes('request-dialog'), 'nothing of the dialog outside the markers');
  assert.ok(!index.slice(0, index.indexOf(START)).includes('plan-request.js'), 'no script tag outside the markers');
});

