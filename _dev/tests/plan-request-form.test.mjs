// ---------- plan-request.js (static; behaviour is proven end to end) ----------

test('plan-request.js never logs, stores or writes a URL, and uses the contract\'s key, header and endpoint', () => {
  assert.equal(spawnSync(process.execPath, ['--check', join(root, 'plan-request.js')], { encoding: 'utf8' }).status, 0);
  assert.doesNotMatch(script, /console/);
  assert.doesNotMatch(script, /localStorage|sessionStorage|indexedDB|document\.cookie/);
  assert.doesNotMatch(script, /location\.(href|search|hash|assign|replace)|history\.(push|replace)State/);
  assert.doesNotMatch(script, /innerHTML/);
  assert.match(script, /crypto\.randomUUID/);
  assert.match(script, /getRandomValues/);
  assert.match(script, /new AbortController\(\)/);
  assert.match(script, /'Idempotency-Key': state\.key/);
  assert.match(script, /'Content-Type': 'application\/json'/);
  assert.match(script, /var ENDPOINT = '\/api\/plan-requests';/);
  assert.match(script, /var DEFAULT_TIMEOUT_MS = 15000;/);
  assert.match(script, /method: 'POST'/);
  assert.ok(script.includes("'La política de privacidad se actualizó. Recargue la página para continuar.'"));
  assert.ok(script.includes(`'${FORM_NOTICE_TEXT}'`));
  assert.ok(script.includes("if (r.ok) { showSuccess(); return; }"), 'any 2xx is success');
  assert.ok(script.includes("if (r.status >= 500) { showRetry(TEXT.server); return; }"), 'a 5xx keeps the key');
  assert.ok(script.includes("function showRetry(text) { state.retry = text; showBanner(text, true); }"), 'a retryable failure is remembered across close/reopen (A2 §2)');
  assert.match(script, /planRequestMode !== 'form'/);
  // Step 8: no cache mode on the POST (N3: it only added request headers); 422 field names looked up as own properties (N6).
  assert.doesNotMatch(script, /cache:/);
  assert.ok(script.includes('function known(field, code) { return Object.hasOwn(MESSAGES, field) && Object.hasOwn(MESSAGES[field], code); }'));
  assert.ok(script.includes('Object.hasOwn(PLAN_FIELDS, f.field)'));
  assert.ok(script.includes('Object.hasOwn(LABELS, e.field)'));
  assert.doesNotMatch(script, /MESSAGES\[field\] &&|PLAN_FIELDS\[f\.field\] \?/, 'a 422 field name must never be looked up through the prototype');
  assert.match(script, /typeof Object\.hasOwn !== 'function'\) return;/, 'a browser without Object.hasOwn keeps the WhatsApp links');
  // The same phone and email rules as the API.
  assert.ok(script.includes('/^\\+?[0-9 ()-]{7,20}$/'));
  assert.ok(script.includes('/^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$/'));
});

