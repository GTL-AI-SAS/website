test('the form follows the live API (A2 §1): limits, kinds of input, method="post", novalidate and no action', () => {
  assert.deepEqual(FIELD_LIMITS, { name: { min: 2, max: 100 }, business: { min: 2, max: 150 }, phone: { max: 20 }, email: { max: 254 }, city: { max: 80 }, message: { max: 500 } });
  assert.equal(PHONE_PATTERN, '^\\+?[0-9 ()-]{7,20}$');
  assert.deepEqual('+57 300 000 0000'.match(new RegExp(PHONE_PATTERN))?.[0], '+57 300 000 0000');
  assert.equal(new RegExp(PHONE_PATTERN).test('abc'), false);
  const html = renderRequestDialog(data, FORM);
  const formTag = html.match(/<form[^>]*>/)[0];
  assert.equal(attr(formTag, 'method'), 'post');
  assert.match(formTag, /\bnovalidate\b/);
  assert.ok(!/ action=/.test(formTag), 'the form must not post anywhere by itself');
  const expect = {
    name: { type: 'text', minlength: '2', maxlength: '100', required: true, autocomplete: 'name' },
    business: { type: 'text', minlength: '2', maxlength: '150', required: true, autocomplete: 'organization' },
    phone: { type: 'tel', maxlength: '20', required: false, autocomplete: 'tel' },
    email: { type: 'email', maxlength: '254', required: false, autocomplete: 'email' },
    city: { type: 'text', maxlength: '80', required: false, autocomplete: 'address-level2' },
  };
  for (const [name, e] of Object.entries(expect)) {
    const tag = inputTag(html, name);
    assert.ok(tag, `${name} input`);
    assert.equal(attr(tag, 'type'), e.type, name);
    assert.equal(attr(tag, 'maxlength'), e.maxlength, name);
    assert.equal(attr(tag, 'minlength'), e.minlength, name);
    assert.equal(/\brequired\b/.test(tag), e.required, name);
    assert.equal(attr(tag, 'autocomplete'), e.autocomplete, name);
    assert.equal(attr(tag, 'id'), `request-${name}`);
    assert.ok(html.includes(`<label for="request-${name}">`), `${name} label`);
    assert.ok(attr(tag, 'aria-describedby').split(' ').includes(`request-${name}-error`), `${name} error region`);
    assert.ok(html.includes(`<p class="request-error" id="request-${name}-error" hidden></p>`), `${name} error element`);
  }
  const message = inputTag(html, 'message');
  assert.equal(attr(message, 'maxlength'), '500');
  assert.ok(html.includes('<label for="request-message">'));
  const plan = inputTag(html, 'plan');
  assert.match(plan, /^<select id="request-plan"/);
  assert.ok(html.includes('<label for="request-plan">'));
  // The reply-time promise comes from the config.
  assert.ok(html.includes(`<p>${FORM.replyTime} Si prefiere, también puede escribirnos por WhatsApp.</p>`));
});

