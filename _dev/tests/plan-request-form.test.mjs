test('every plan option carries the WhatsApp link of its button, and the general enquiry comes first', () => {
  const options = planOptions(data, FORM);
  assert.equal(options.length, 21);
  assert.deepEqual(options[0], { value: 'general', label: 'Ayuda para elegir un plan', group: null, href: 'https://wa.me/573001234567?text=' + encodeURIComponent('Hola, quiero ayuda para elegir un plan (gtl-ai.com)') });
  const section = renderSection(data, FORM);
  const hrefOf = (sel) => attr((section.match(new RegExp(`<a class="btn[^"]*"[^>]*${sel}[^>]*>`)) || [])[0] || '', 'href');
  for (const o of options) {
    const [kind, a, b] = o.value.split(':');
    const sel = kind === 'plan' ? `data-package="${a}" data-tier="${b}"` : kind === 'bundle' ? `data-bundle="${a}"` : 'data-general="true"';
    assert.equal(o.href, hrefOf(sel).replace(/&amp;/g, '&'), o.value);
  }
  const labels = options.map((o) => o.label);
  assert.ok(labels.includes('Agenda · Crece') && labels.includes('Proyecto a medida') && labels.includes('Clínica Completa'));
  const groups = [...new Set(options.map((o) => o.group))];
  assert.deepEqual(groups, [null, 'Agenda', 'Presencia', 'Pedidos', 'Reservas', 'Comunidad', 'A medida', 'Paquetes por sector']);
  // Rendered: one <option> per request, each with data-whatsapp.
  const dialog = renderRequestDialog(data, FORM);
  assert.equal((dialog.match(/<option value="/g) || []).length, 21);
  assert.equal((dialog.match(/ data-whatsapp="https:\/\/wa\.me\/573001234567\?text=/g) || []).length, 21);
  // Messages follow the data: a renamed tier shows up in its option and its link.
  const fixture = structuredClone(data);
  fixture.packages.find((p) => p.code === 'pedidos').tiers.find((t) => t.code === 'pro').name = 'Pro Plus';
  const renamed = planOptions(fixture, FORM).find((o) => o.value === 'plan:pedidos:pro');
  assert.equal(renamed.label, 'Pedidos · Pro Plus');
  assert.equal(decodeURIComponent(renamed.href.split('?text=')[1]), 'Hola, quiero información del plan Pedidos · Pro Plus (gtl-ai.com)');
});

